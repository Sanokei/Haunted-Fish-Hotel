"""Update authored recording YAML without running Unity. Native import remains required.

Only tutorial assets are written. Production prefabs, scene and all existing .meta
identities are preserved. No gameplay/capture/evidence is generated by this tool.
"""
from pathlib import Path
import re
import sys
import uuid

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'Tools/ScenePresentationTests'))
import verify_scene_assets as assets


def guid(path):
    return re.search(r'^guid: (\w+)', (ROOT / (path + '.meta')).read_text(), re.M)[1]


def records(text):
    return {record.ident: record for record in assets.records(text)}


def replace_record(text, ident, new):
    return re.sub(r'^--- !u!\d+ &' + str(ident) + r'(?: stripped)?\n[\s\S]*?(?=^--- |\Z)', lambda _: new, text, flags=re.M)


def ref(ident, asset_guid):
    return '{fileID: ' + str(ident) + ', guid: ' + asset_guid + ', type: 3}'


def main():
    trap_script = guid('Assets/Scripts/Multiplayer/GhostTrap.cs')
    definitions = {}
    for source, target in [('ShoppingCartTrap', 'TutorialCart'), ('FallingChandelierTrap', 'TutorialChandelier'), ('ClickTrap', 'TutorialClickTrap'), ('AnglerFishTrap', 'TutorialAngler')]:
        path = f'Assets/Resources/Tutorials/{target}.prefab'
        text = (ROOT / f'Assets/Resources/Traps/{source}.prefab').read_text()
        parsed = records(text)
        trap = next(record for record in parsed.values() if 'guid: ' + trap_script in record.body)
        if source == 'FallingChandelierTrap':
            collider = parsed[assets.local_ref(trap.body, '_Collider')]
            size_y = float(re.search(r'^  m_Size: \{x: [^,]+, y: ([^,]+),', collider.body, re.M)[1])
            fall = 4.11 - size_y
            text = re.sub(r'^  _ArmedOffset:.*$', f'  _ArmedOffset: {{x: 0, y: {fall:.6g}, z: 0}}', text, flags=re.M)
            text = re.sub(r'^  _FallDistance:.*$', f'  _FallDistance: {fall:.6g}', text, flags=re.M)
        meta = ROOT / (path + '.meta')
        if not meta.exists():
            meta.write_text('fileFormatVersion: 2\nguid: ' + uuid.uuid5(uuid.NAMESPACE_URL, 'haunted-fish-hotel/' + path).hex + '\nPrefabImporter:\n  externalObjects: {}\n  userData: \n  assetBundleName: \n  assetBundleVariant: \n')
        assert not assets.syntax_issues(text), path
        assert not assets.reference_issues(text), path
        (ROOT / path).write_text(text)
        definitions[target] = (trap.ident, guid(path))

    stage_path = ROOT / 'Assets/Resources/Tutorials/TutorialRecordingStage.prefab'
    text = stage_path.read_text()
    # Diagnostic recording captions share the original intertitle font; final intertitles
    # are authored offline, and these baked caption regions are cropped out.
    intertitle = guid("Assets/Art/Fonts/HauntedIntertitle-Regular.ttf")
    text = re.sub(r"(m_Font: \{fileID: 12800000, guid: )[a-f0-9]+", r"\g<1>" + intertitle, text)
    parsed = records(text)
    root = 4173343303930472214
    first_instance = 1082790918396331093
    first_transform = 1082790918383741719
    first_actor = 1082790918383741712
    second_instance, second_transform, second_actor = 95001001, 95001002, 95001003
    stun_root, stun_animation, haunting = 95001011, 95001012, 95001020
    shot_go, shot_transform = 95001030, 95001031
    player_guid = guid('Assets/Resources/HotelNetworkPlayer.prefab')
    player_script = guid('Assets/Scripts/Multiplayer/HotelPlayer.cs')

    # Replace all existing references to the stable tutorial asset GUIDs with their
    # production-derived component fileIDs (the earlier copies were flattened).
    for ident, asset_guid in definitions.values():
        text = re.sub(r'\{fileID: \d+, guid: ' + asset_guid + r', type: 3\}', ref(ident, asset_guid), text)
    parsed = records(text)
    first = parsed[first_instance].body
    first = re.sub(r'(propertyPath: m_Enabled\n      value:) 0', r'\1 1', first)
    text = replace_record(text, first_instance, f'--- !u!1001 &{first_instance}\n' + first)
    if second_instance not in parsed:
        clone = first.replace('value: Authored fish - production motor', 'value: Authored second fish - production impact target')
        text += f'--- !u!1001 &{second_instance}\n' + clone
        for kind, ident, source in [(4, second_transform, 21000002), (114, second_actor, 21000005), (1, stun_root, 883400003), (111, stun_animation, 883400004)]:
            instance = second_instance if ident in (second_transform, second_actor) else first_instance
            type_name = {4: 'Transform', 114: 'MonoBehaviour', 1: 'GameObject', 111: 'Animation'}[kind]
            text += f'--- !u!{kind} &{ident} stripped\n{type_name}:\n  m_CorrespondingSourceObject: ' + ref(source, player_guid) + f'\n  m_PrefabInstance: {{fileID: {instance}}}\n  m_PrefabAsset: {{fileID: 0}}\n'
            if kind == 114:
                text += '  m_GameObject: {fileID: 0}\n  m_Enabled: 1\n  m_EditorHideFlags: 0\n  m_Script: ' + ref(11500000, player_script) + '\n  m_Name: \n  m_EditorClassIdentifier: \n'
    parsed = records(text)
    director_id = 242606801975031782
    director = parsed[director_id].body
    if '  OtherFish:' not in director:
        director = director.replace('  Fish: {fileID: ' + str(first_actor) + '}', '  Fish: {fileID: ' + str(first_actor) + '}\n  OtherFish: {fileID: ' + str(second_actor) + '}\n  Haunting: {fileID: ' + str(haunting) + '}\n  FishStunEffect: {fileID: ' + str(stun_root) + '}\n  FishStunAnimation: {fileID: ' + str(stun_animation) + '}')
    if '  AnglerDefinition:' not in director:
        director = director.replace('  Hallway:', '  AnglerDefinition: ' + ref(*definitions['TutorialAngler']) + '\n  Hallway:')
    if '  - Name: trap-wide' not in director:
        director = director.replace('  CameraEase:', f'  - Name: trap-wide\n    Pose: {{fileID: {shot_transform}}}\n    FieldOfView: 46\n    Orthographic: 1\n    Size: 4\n  CameraEase:')
    director = re.sub(r'(  - Name: ceiling\n[\s\S]*?    Size:) [^\n]+', r'\1 3.5', director)
    text = replace_record(text, director_id, f'--- !u!114 &{director_id}\n' + director)
    world = parsed[7555351392353907708].body
    all_traps = '\n'.join('  - ' + ref(*definitions[name]) for name in ('TutorialCart', 'TutorialChandelier', 'TutorialClickTrap', 'TutorialAngler'))
    world = re.sub(r'^  _TrapPrefabs:[\s\S]*?(?=^  _TrapContainer:)', '  _TrapPrefabs:\n' + all_traps + '\n', world, flags=re.M)
    text = replace_record(text, 7555351392353907708, '--- !u!114 &7555351392353907708\n' + world)
    world_go = parsed[1188112850407518979].body
    if f'component: {{fileID: {haunting}}}' not in world_go:
        world_go = world_go.replace('  m_Layer:', f'  - component: {{fileID: {haunting}}}\n  m_Layer:')
    text = replace_record(text, 1188112850407518979, '--- !u!1 &1188112850407518979\n' + world_go)
    if haunting not in parsed:
        text += f'--- !u!114 &{haunting}\nMonoBehaviour:\n  m_ObjectHideFlags: 0\n  m_CorrespondingSourceObject: {{fileID: 0}}\n  m_PrefabInstance: {{fileID: 0}}\n  m_PrefabAsset: {{fileID: 0}}\n  m_GameObject: {{fileID: 1188112850407518979}}\n  m_Enabled: 1\n  m_EditorHideFlags: 0\n  m_Script: ' + ref(11500000, guid('Assets/Scripts/Multiplayer/GameHauntingController.cs')) + '\n  m_Name: \n  m_EditorClassIdentifier: Assembly-CSharp::HauntedFish.Multiplayer.GameHauntingController\n  _ContactDamagePerSecond: 50\n'
    if shot_go not in parsed:
        # Copy the existing floor shot's authored GameObject/Transform shapes.
        source_transform = parsed[6249021459675144684]
        source_go_id = assets.local_ref(source_transform.body, 'm_GameObject')
        source_go = parsed[source_go_id]
        body = source_go.body.replace('Camera shot - floor', 'Camera shot - trap-wide').replace(str(6249021459675144684), str(shot_transform))
        text += f'--- !u!1 &{shot_go}\n' + body
        body = source_transform.body.replace(str(source_go_id), str(shot_go))
        body = re.sub(r'^  m_LocalPosition:.*$', '  m_LocalPosition: {x: -1, y: 1.8, z: -18}', body, flags=re.M)
        text += f'--- !u!4 &{shot_transform}\n' + body
    root_body = parsed[root].body
    for child in (second_transform, shot_transform):
        if f'  - {{fileID: {child}}}' not in root_body:
            root_body = root_body.replace('  m_Father:', f'  - {{fileID: {child}}}\n  m_Father:')
    text = replace_record(text, root, f'--- !u!4 &{root}\n' + root_body)
    assert not assets.syntax_issues(text), assets.syntax_issues(text)
    assert not assets.reference_issues(text), assets.reference_issues(text)
    stage_path.write_text("\n".join(line.rstrip() for line in text.splitlines()) + "\n")
    print('Authored tutorial trap copies/stage updated. Existing linked scene inherits them. Native import, physics and capture are still unverified.')


if __name__ == '__main__': main()
